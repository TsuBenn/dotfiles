#include <stdio.h>

int main() {

    int n;
    scanf("%d",&n);

    printf("\nOUTPUT:\n");
    if (n >= 90) {
        printf("A");
    } 
    else if (n >= 80) {
        printf("B");
    } 
    else if (n >= 70) {
        printf("C");
    } 
    else if (n >= 60) {
        printf("D");
    } 
    else if (n >= 0) {
        printf("E");
    } 


}

